import type { Database } from "../db";
import { addDays, todayInTz, type IsoDate } from "@/lib/dates";
import { NORTHSTAR } from "./data";
import { createNorthstarMaster, upsertRoles } from "./master";
import { openingBalances, simulate } from "./simulate";
import { todayScenarios } from "./scenario";
import { seedCobalt } from "./cobalt";
import { createRng, SeedClock, startOfDayInstant } from "./util";

export interface SeedOptions {
  /** Business date treated as "today" (defaults to the current date in the org timezone). */
  today?: IsoDate;
  /** Days of history to simulate. */
  days?: number;
  log?: (msg: string) => void;
  /** Skip the second tenant (faster tests). */
  skipSecondTenant?: boolean;
}

/**
 * Seed the fictional demo tenants. History is generated by replaying operations through
 * the service layer with a simulated clock, so balances, ledgers, KPIs and charts
 * reconcile by construction. Dates are relative to "today".
 */
export async function seedDemo(db: Database, opts: SeedOptions = {}) {
  const log = opts.log ?? (() => {});
  const realNow = new Date();
  const today = opts.today ?? todayInTz(NORTHSTAR.timezone, realNow);
  const days = opts.days ?? 180;
  const start = addDays(today, -days);
  const rng = createRng(20240917);
  const clock = new SeedClock();
  const t0 = Date.now();

  await upsertRoles(db);
  log(`Seeding Northstar Precision Manufacturing (${start} → ${today})`);
  const world = await createNorthstarMaster(db, clock, addDays(start, -45));
  clock.set(new Date(startOfDayInstant(start, NORTHSTAR.timezone).getTime() + 6 * 3_600_000));
  await openingBalances(db, world, rng, start);
  await simulate(db, world, rng, clock, start, addDays(today, -1), log);

  // Today's activity happens shortly before the real current time (never in the future).
  const dayStart = startOfDayInstant(today, NORTHSTAR.timezone).getTime();
  const base = opts.today ? dayStart + 8 * 3_600_000 : Math.max(dayStart + 60_000, realNow.getTime() - 100 * 60_000);
  clock.set(new Date(base));
  await todayScenarios(db, world, rng, today, log);

  if (!opts.skipSecondTenant) {
    await seedCobalt(db, clock, today, world.people.avery.id);
    log("Seeded Cobalt Ridge Fabrication (second tenant)");
  }
  await db.query(
    `update organizations set settings = settings || jsonb_build_object('seededAt', $1::text, 'seededFor', $2::text) where is_demo`,
    [realNow.toISOString(), today],
  );
  log(`Seed complete in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  return { orgId: world.org.id, today };
}
